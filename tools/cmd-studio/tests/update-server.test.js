'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const storage=fs.mkdtempSync(path.join(os.tmpdir(),'cmd-studio-feed-test-'));
process.env.CMD_STUDIO_UPDATE_STORAGE=storage;
process.env.CMD_STUDIO_UPDATE_READ_TOKEN='local-test-private-read-token-123456';
process.env.CMD_STUDIO_UPDATE_WRITE_TOKEN='local-test-private-write-token-123456';
const {createServer,auth,clean}=require('../private-update-server.cjs');
test('serveur de mises à jour : authentification obligatoire, lecture et range',async t=>{
  t.after(()=>fs.rmSync(storage,{recursive:true,force:true}));
  const server=createServer();
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>server.close());
  const base='http://127.0.0.1:'+server.address().port+'/updates/cmd-studio/';
  const filename='CMD Studio Setup 0.2.2.exe';
  const bytes=Buffer.from('MZ'+'test-of-private-windows-release');
  const unauthorized=await fetch(base+'latest.yml');
  assert.equal(unauthorized.status,401);
  const url=base+encodeURIComponent(filename);
  const upload=await fetch(url,{method:'PUT',headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_WRITE_TOKEN},body:bytes});
  assert.equal(upload.status,201);
  const read=await fetch(url,{headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_READ_TOKEN}});
  assert.equal(read.status,200);
  assert.equal(await read.text(),bytes.toString());
  const ranged=await fetch(url,{headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_READ_TOKEN,Range:'bytes=0-1'}});
  assert.equal(ranged.status,206);
  assert.equal(await ranged.text(),'MZ');
  assert.equal((await fetch(url,{headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_WRITE_TOKEN}})).status,401);
  const manifest=await fetch(base+'latest.yml',{method:'PUT',headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_WRITE_TOKEN},body:'version: 0.2.2\nfiles:\n- sha512: ab\nsignature: abc\n'});
  assert.equal(manifest.status,201);
  assert.equal((await fetch(base+'latest.yml',{headers:{Authorization:'Bearer '+process.env.CMD_STUDIO_UPDATE_READ_TOKEN}})).status,200);
});
test('serveur privé : rejette traversal et mauvais jetons',()=>{
  assert.equal(auth('Bearer local-test-private-read-token-123456',process.env.CMD_STUDIO_UPDATE_READ_TOKEN),true);
  assert.equal(auth('Bearer nope',process.env.CMD_STUDIO_UPDATE_READ_TOKEN),false);
  assert.throws(()=>clean('../config.json'));
  assert.throws(()=>clean('secret.txt'));
  assert.throws(()=>clean('a..b.exe'));
});
