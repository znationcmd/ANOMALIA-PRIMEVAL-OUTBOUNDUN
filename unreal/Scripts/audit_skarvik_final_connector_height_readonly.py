"""READ ONLY: scan first 20 genuine SKARVIK road-to-town connector candidates
against the compiled UE5 final-coast height function.

Runs only inside Unreal Editor Python in the *trusted isolated C staging
project*, never D:\ANOMALIA, and never calls asset save or actor spawn.
Source inputs are generated by scripts/skarvik_design_missing_connectors.py.
This is an audit, NOT construction or proof of drivable roads.
"""
import hashlib
import json
import math
import os
from pathlib import Path

import unreal

PROJECT=Path(unreal.Paths.project_dir()).resolve()
EXPECTED="C:/ANOMALIAZ_SKARVIK_STAGE_41188816555/unreal"
STAGE=Path(os.environ["SKARVIK_NATIVE_NEW_CONNECTORS_INPUT"]).resolve()
OUTPUT=Path(os.environ["SKARVIK_NATIVE_NEW_CONNECTORS_REPORT"]).resolve()
WORLD="/Game/Maps/PRIGIMALIA_SKARVIK_FINAL_v1"

SOURCES=(
    PROJECT/"Content/Maps/PRIGIMALIA_SKARVIK_FINAL_v1.umap",
    PROJECT/"Content/Maps/PRIGIMALIA_SKARVIK_GRADED_v2.umap",
    PROJECT/"Content/Maps/PRIGIMALIA_SKARVIK_ISLANDS_v1.umap",
    PROJECT/"Content/Map/Big_City_LVL.umap",
    Path("D:/ANOMALIA/unreal/Content/Maps/ANOMALIA_Archipelago_v2.umap"),
)
REPORT={"schemaVersion":1,"world":"SKARVIK","state":"FAILED",
        "readOnly":True,"sourceWorldsUnchanged":False,"candidates":[],
        "routeMeshesPlaced":0,"levelSaved":False,
        "vehicleDriveValidated":False,"buildingCollisionValidated":False}


def sha256(path):
    h=hashlib.sha256()
    with path.open("rb") as f:
        while True:
            b=f.read(1024*1024)
            if not b:break
            h.update(b)
    return h.hexdigest()


def check():
    if PROJECT.as_posix().lower()!=EXPECTED.lower():
        raise RuntimeError("Wrong Unreal project path: staging C copy only")
    marker=PROJECT/".skarvik-ci-stage-marker"
    if not marker.is_file() or marker.read_text(encoding="utf-8-sig").strip()!="41188816555":
        raise RuntimeError("Untrusted staging marker")
    for f in SOURCES:
        if not f.is_file():
            raise RuntimeError("Missing protected level: "+str(f))
    if not STAGE.is_file() or STAGE.suffix.lower()!=".json":
        raise RuntimeError("Missing independent coastline design report")
    originals={str(p):sha256(p) for p in SOURCES}
    data=json.loads(STAGE.read_text(encoding="utf-8-sig"))
    if (data.get("world")!="SKARVIK" or data.get("extentKm")!=[48,48] or
        data.get("regionalRoutes")!=382 or data.get("existingTownCount")!=125 or
        data.get("routesDisconnectedBeyond250M")!=236 or
        data.get("routesWithoutPolyline")!=137 or
        data.get("sourceLevel")!=WORLD):
        raise RuntimeError("Invalid original route/settlement audit")
    candidates=data.get("first20SurveyCandidates")
    if not isinstance(candidates,list) or len(candidates)>20:
        raise RuntimeError("Invalid short review batch")
    native=unreal.AnomaliaZPrigimaliaWorldImportLibrary
    if not hasattr(native,"skarvik_final_coastal_height"):
        raise RuntimeError("Compiled native SKARVIK coast sampler is absent")
    lv=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if not lv.load_level(WORLD):
        raise RuntimeError("Unable to reopen real final coastal World Partition")
    # The height function returns METRES for x/y expressed in METRES.
    def height(x,y):
        h=float(native.skarvik_final_coastal_height(x,y))
        if not math.isfinite(h):
            raise RuntimeError("Non-finite native Landscape surface")
        return h
    output=[]
    for c in candidates:
        if c.get("approvedForNativeAsphaltBuild") is not False:
            raise RuntimeError("Unexpected author-approved road")
        a=c["sourcePolylineEndpointKm"]
        b=c["newSettlementCenterKm"]
        dx=(b[0]-a[0])*1000.
        dy=(b[1]-a[1])*1000.
        length=math.hypot(dx,dy)
        samples=max(2,math.ceil(length/20))
        states=[]
        last=None
        for step in range(samples+1):
            t=step/samples
            x=(a[0]+(b[0]-a[0])*t)*1000
            y=(a[1]+(b[1]-a[1])*t)*1000
            h=height(x,y)
            if h<5:states.append("SEA_OR_COAST")
            if last is not None:
                slope=abs(h-last[2])/max(1,math.hypot(x-last[0],y-last[1]))
                if slope>.12:states.append("STEEP_GRADE")
            # Keep the 4x4 km City Sample urban footprint untouched. Its
            # roads require visual inspection of authentic city static meshes.
            if 0<=x/1000<=4 and -10<=y/1000<=-6:
                states.append("PRESERVE_CITYSAMPLE_4KM_BOUNDS")
            last=(x,y,h)
        output.append({
            "candidateId":c["id"],"roadId":c["routeId"],
            "settlementId":c["settlementId"],"metres":round(length,2),
            "heightSamples":samples+1,"warnings":sorted(set(states)),
            "needsBuildingCollisionSurvey":True,
            "needsSM5VehicleDriveTest":True,
            "nativeRoadBuilt":False,
            "class":"NATIVE_HEIGHT_SURVEY_PASSES_STILL_REQUIRES_COLLISIONS"
                    if not states else "NATIVE_HEIGHT_OR_CITY_CONFLICT",
        })
    REPORT.update(state="READONLY_NATIVE_FINAL_COAST_CONNECTOR_HEIGHT_SURVEY_COMPLETE",
                  inspected=len(output),candidates=output,
                  sourceWorldsUnchanged=all(sha256(p)==originals[str(p)] for p in SOURCES),
                  citySampleAssetsModified=False,
                  sevenIslandOriginalLevelsModified=False)
    if not REPORT["sourceWorldsUnchanged"]:
        raise RuntimeError("A protected native map changed during read-only survey")


try:
    check()
except Exception as error:
    REPORT["error"]=str(error)
finally:
    if OUTPUT.parent.is_dir() and not OUTPUT.exists():
        OUTPUT.write_text(json.dumps(REPORT,ensure_ascii=False,indent=2)+"\n",
                          encoding="utf-8")
    unreal.log("SKARVIK_NATIVE_CONNECTOR_SURVEY_STATE="+REPORT["state"])
